#!/usr/bin/env python3
"""Converts test/vectors/*.json into test/vectors.h.

The generated header is committed so the tests need neither Python nor a JSON
parser. Re-run this script when the BIP updates its vectors.
"""

import json
import os
import shutil
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
VECTORS = os.path.join(HERE, "vectors")
OUT = os.path.join(HERE, "vectors.h")

HARDENED = 0x80000000


def load(name):
    with open(os.path.join(VECTORS, name + ".json"), encoding="utf-8") as f:
        return json.load(f)


class Emitter:
    def __init__(self):
        self.lines = []
        self.counter = 0

    def emit(self, line=""):
        self.lines.append(line)

    def fresh(self, prefix):
        self.counter += 1
        return "%s_%d" % (prefix, self.counter)

    def byte_array(self, prefix, data):
        """Emits a uint8_t array and returns the tv_bytes initializer."""
        if data is None:
            return "{NULL, 0}"
        if len(data) == 0:
            return "{tv_empty, 0}"
        name = self.fresh(prefix)
        body = ", ".join("0x%02x" % b for b in data)
        self.emit("static const uint8_t %s[] = {%s};" % (name, body))
        return "{%s, %d}" % (name, len(data))

    def paths(self, prefix, paths):
        """Emits flattened paths and returns the tv_paths initializer."""
        if paths is None:
            return "{NULL, NULL, 0}"
        if len(paths) == 0:
            return "{NULL, tv_empty_depths, 0}"
        children = []
        depths = []
        for p in paths:
            comps = parse_path(p)
            children.extend(comps)
            depths.append(len(comps))
        name = self.fresh(prefix)
        self.emit("static const uint32_t %s_children[] = {%s};" %
                  (name, ", ".join("0x%08xu" % c for c in children) or "0"))
        self.emit("static const uint16_t %s_depths[] = {%s};" %
                  (name, ", ".join(str(d) for d in depths)))
        return "{%s_children, %s_depths, %d}" % (name, name, len(paths))


def parse_path(path):
    parts = path.split("/")
    if parts[0] != "m":
        raise ValueError(path)
    out = []
    for comp in parts[1:]:
        hardened = comp.endswith("'") or comp.endswith("h")
        if hardened:
            comp = comp[:-1]
        value = int(comp)
        out.append(value | HARDENED if hardened else value)
    return out


def hexbytes(value):
    return None if value is None else bytes.fromhex(value)


def xonly(compressed_hex):
    key = bytes.fromhex(compressed_hex)
    if len(key) == 33:
        return key[1:]
    if len(key) == 32:
        return key
    raise ValueError(compressed_hex)


def cstr(text):
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return '"%s"' % escaped


def main():
    e = Emitter()
    e.emit("/* Generated by test/gen_vectors.py from the JSON files in test/vectors. */")
    e.emit("#ifndef BIP138_TEST_VECTORS_H")
    e.emit("#define BIP138_TEST_VECTORS_H")
    e.emit("#include <stddef.h>")
    e.emit("#include <stdint.h>")
    e.emit()
    e.emit("typedef struct { const uint8_t *p; size_t n; } tv_bytes;")
    e.emit("typedef struct { const uint32_t *children; const uint16_t *depths;"
           " size_t n; } tv_paths;")
    e.emit("static const uint8_t tv_empty[1] = {0};")
    e.emit("static const uint16_t tv_empty_depths[1] = {0};")
    e.emit()

    # encryption_secret.json
    e.emit("typedef struct { const char *desc; tv_bytes keys; tv_bytes secret;"
           " tv_bytes individual; } tv_encryption_secret;")
    rows = []
    for v in load("encryption_secret"):
        keys = b"".join(xonly(k) for k in v["keys"])
        individual = b"".join(bytes.fromhex(s) for s in v["individual_secrets"])
        rows.append("{%s, %s, %s, %s}" % (
            cstr(v["description"]), e.byte_array("tv_es_keys", keys),
            e.byte_array("tv_es_secret", hexbytes(v["decryption_secret"])),
            e.byte_array("tv_es_ind", individual)))
    e.emit("static const tv_encryption_secret tv_encryption_secret_vectors[] = "
           "{%s};" % ", ".join(rows))
    e.emit("#define TV_ENCRYPTION_SECRET_COUNT %d" % len(rows))
    e.emit()

    # individual_secrets.json
    e.emit("typedef struct { const char *desc; tv_bytes secrets; tv_bytes expected;"
           " } tv_individual_secrets;")
    rows = []
    for v in load("individual_secrets"):
        secrets = b"".join(bytes.fromhex(s) for s in v["secrets"])
        rows.append("{%s, %s, %s}" % (
            cstr(v["description"]), e.byte_array("tv_is_secrets", secrets),
            e.byte_array("tv_is_expected", hexbytes(v["expected"]))))
    e.emit("static const tv_individual_secrets tv_individual_secrets_vectors[] "
           "= {%s};" % ", ".join(rows))
    e.emit("#define TV_INDIVIDUAL_SECRETS_COUNT %d" % len(rows))
    e.emit()

    # derivation_path.json
    e.emit("typedef struct { const char *desc; tv_paths paths; tv_bytes expected;"
           " } tv_derivation_path;")
    rows = []
    for v in load("derivation_path"):
        rows.append("{%s, %s, %s}" % (
            cstr(v["description"]), e.paths("tv_dp", v["paths"]),
            e.byte_array("tv_dp_expected", hexbytes(v["expected"]))))
    e.emit("static const tv_derivation_path tv_derivation_path_vectors[] = {%s};"
           % ", ".join(rows))
    e.emit("#define TV_DERIVATION_PATH_COUNT %d" % len(rows))
    e.emit()

    # content_type.json
    e.emit("typedef struct { const char *desc; int valid; tv_bytes content; }"
           " tv_content_type;")
    rows = []
    for v in load("content_type"):
        rows.append("{%s, %d, %s}" % (
            cstr(v["description"]), 1 if v["valid"] else 0,
            e.byte_array("tv_ct", hexbytes(v["content"]))))
    e.emit("static const tv_content_type tv_content_type_vectors[] = {%s};"
           % ", ".join(rows))
    e.emit("#define TV_CONTENT_TYPE_COUNT %d" % len(rows))
    e.emit()

    # chacha20poly1305_encryption.json
    e.emit("typedef struct { const char *desc; tv_bytes nonce; tv_bytes plaintext;"
           " tv_bytes secret; tv_bytes ciphertext; } tv_chacha;")
    rows = []
    for v in load("chacha20poly1305_encryption"):
        rows.append("{%s, %s, %s, %s, %s}" % (
            cstr(v["description"]), e.byte_array("tv_cc_nonce", hexbytes(v["nonce"])),
            e.byte_array("tv_cc_pt", hexbytes(v["plaintext"])),
            e.byte_array("tv_cc_secret", hexbytes(v["secret"])),
            e.byte_array("tv_cc_ct", hexbytes(v["ciphertext"]))))
    e.emit("static const tv_chacha tv_chacha_vectors[] = {%s};" % ", ".join(rows))
    e.emit("#define TV_CHACHA_COUNT %d" % len(rows))
    e.emit()

    # encrypted_backup.json
    e.emit("typedef struct { tv_bytes content; tv_bytes plaintext; } tv_backup_item;")
    e.emit("#define TV_BACKUP_MAX_ITEMS 4")
    e.emit("typedef struct { const char *desc; int valid; tv_bytes keys;"
           " tv_bytes decoys; tv_paths paths; tv_backup_item items[TV_BACKUP_MAX_ITEMS];"
           " size_t n_items; tv_bytes nonce; tv_bytes expected;"
           " const char *expected_base64; tv_bytes trailing; } tv_backup;")
    rows = []
    for v in load("encrypted_backup"):
        if v.get("version", 1) != 1 or v.get("encryption", 1) != 1:
            raise ValueError("unsupported vector version")
        keys = b"".join(xonly(k) for k in v["keys"])
        decoys = b"".join(bytes.fromhex(s) for s in v["decoy_individual_secrets"])
        items = [(hexbytes(v["content"]), v["plaintext"].encode("utf-8"))]
        for extra in v.get("extra", []):
            items.append((hexbytes(extra["content"]),
                          extra["plaintext"].encode("utf-8")))
        if len(items) > 4:
            raise ValueError("raise TV_BACKUP_MAX_ITEMS")
        item_inits = ["{%s, %s}" % (e.byte_array("tv_eb_content", c),
                                    e.byte_array("tv_eb_pt", p)) for c, p in items]
        while len(item_inits) < 4:
            item_inits.append("{{NULL, 0}, {NULL, 0}}")
        rows.append("{%s, %d, %s, %s, %s, {%s}, %d, %s, %s, %s, %s}" % (
            cstr(v["description"]), 1 if v.get("valid", True) else 0,
            e.byte_array("tv_eb_keys", keys), e.byte_array("tv_eb_decoys", decoys),
            e.paths("tv_eb", v["derivation_paths"]), ", ".join(item_inits),
            len(items), e.byte_array("tv_eb_nonce", hexbytes(v["nonce"])),
            e.byte_array("tv_eb_expected", hexbytes(v["expected"])),
            cstr(v["expected_base64"]),
            e.byte_array("tv_eb_trailing", hexbytes(v.get("trailing")))))
    e.emit("static const tv_backup tv_backup_vectors[] = {%s};" % ", ".join(rows))
    e.emit("#define TV_BACKUP_COUNT %d" % len(rows))
    e.emit()

    # keys_types.json
    e.emit("typedef struct { const char *desc; const char *key; tv_bytes expected; }"
           " tv_key_type;")
    rows = []
    for v in load("keys_types"):
        rows.append("{%s, %s, %s}" % (
            cstr(v["description"]), cstr(v["key"]),
            e.byte_array("tv_kt_expected", hexbytes(v["expected"]))))
    e.emit("static const tv_key_type tv_key_type_vectors[] = {%s};"
           % ", ".join(rows))
    e.emit("#define TV_KEY_TYPE_COUNT %d" % len(rows))
    e.emit()
    e.emit("#endif /* BIP138_TEST_VECTORS_H */")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(e.lines) + "\n")
    if shutil.which("clang-format"):
        subprocess.run(["clang-format", "-i", OUT], check=True)


if __name__ == "__main__":
    main()
